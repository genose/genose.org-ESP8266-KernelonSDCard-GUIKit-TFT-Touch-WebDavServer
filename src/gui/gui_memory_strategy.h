// ============================================================================
// Memory Strategy Result
// ============================================================================

typedef struct {
    MemoryStrategyLevel level;        // Which strategy was used
    bool success;                      // Whether loading succeeded
    uint32_t gui_size;                // Size of GUI JSON in bytes
    uint32_t memory_used;             // Memory used by this strategy
    const char* storage_location;    // Human-readable location
    
    // Strategy-specific data
    union {
        struct {
            uint32_t sram_addr;        // Address in external RAM
            SPISRAM* sram;            // SRAM instance used
        } external_ram;
        
        struct {
            const char* filepath;     // Path on SD card
            uint32_t cache_addr;       // Cache address in internal RAM
            uint32_t cache_size;       // Size of cached data
        } sd_swap;
        
        struct {
            void* gui_ptr;            // Pointer to GUI in internal RAM
        } internal_ram;
    } data;
    
    const char* error_message;        // Error message if failed
} MemoryStrategyResult;

