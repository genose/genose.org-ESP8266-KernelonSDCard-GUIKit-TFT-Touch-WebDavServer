/**
 * GUIKit Memory Strategy
 * 
 * Hierarchical memory management for GUI data:
 * 1. External RAM (23LC1024 SRAM) - Primary storage
 * 2. SD Card Swap - Secondary storage (for large GUIs)
 * 3. Internal RAM - Fallback storage
 * 
 * Strategy (STOP at first success):
 * 1. Try External RAM: if (available AND GUI fits AND can_use) => SELECT & STOP
 * 2. Try SD Card Swap: if (available AND GUI fits AND can_use) => SELECT & STOP
 * 3. Try Internal RAM: if (GUI fits AND can_use) => SELECT & STOP
 * 4. Else => FAILED
 * 
 * Key principle: Each strategy is tried in order, and the FIRST SUCCESS
 * becomes the selected strategy. The process STOPS at the first success.
 * 
 * Generated by Mistral Vibe
 * Date: 2026-08-15
 */

