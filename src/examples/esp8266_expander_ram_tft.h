#define SRAM_CS_PIN    1   // TX (GPIO1) - Using serial TX pin as GPIO

// SD Card Pins
#define SD_CS_PIN     16  // D0 (GPIO16)

// Shared SPI Pins (Hardware SPI)
#define SPI_SCK_PIN    14  // D5 (GPIO14)
#define SPI_MOSI_PIN   13  // D7 (GPIO13)
#define SPI_MISO_PIN   12  // D6 (GPIO12)

// SPI Speed
#define SPI_MAX_SPEED_MHZ 20

