/**
 * ESP8266 + MCP23S17 + 23LC1024 + TFT + Touch + SD Card Example Configuration
 * 
 * Example hardware configuration for ESP8266 (NodeMCU v2) with:
 * - MCP23S17 GPIO Expander (16 additional GPIO pins)
 * - 23LC1024 SPI SRAM (128 KB external RAM)
 * - TFT ST7789 Display (320x240)
 * - XPT2046 Touch Controller
 * - SD Card (SPI mode)
 * 
 * This example demonstrates how to configure and initialize all five
 * SPI devices on the shared SPI bus of ESP8266.
 * 
 * Wiring:
 * - TFT: CS=D8(GPIO15), DC=D3(GPIO0), SCK=D5, MOSI=D7, MISO=D6
 * - Touch: CS=D2(GPIO4), IRQ=D1(GPIO5), SCK=D5, MOSI=D7, MISO=D6
 * - MCP23S17: CS=RX(GPIO3), SCK=D5, MOSI=D7, MISO=D6
 * - 23LC1024: CS=TX(GPIO1), SCK=D5, MOSI=D7, MISO=D6
 * - SD Card: CS=D0(GPIO16), SCK=D5, MOSI=D7, MISO=D6
 * 
 * Note: All 5 devices share SCK, MOSI, MISO. Each has unique CS line.
 * RX (GPIO3) and TX (GPIO1) are used as GPIO for CS lines.
 * 
 * Generated by Mistral Vibe
 * Date: 2026-08-15
 */

