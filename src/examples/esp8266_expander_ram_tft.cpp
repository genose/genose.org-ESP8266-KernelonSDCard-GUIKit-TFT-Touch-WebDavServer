void setup() {
    Serial.begin(115200);
    while (!Serial);
    
    Serial.println("ESP8266 + MCP23S17 + 23LC1024 + TFT + Touch + SD Card Example");
    Serial.println("==============================================================");
    
    // Choose one initialization method:
    initHardwareFromUnionConfig();
    // initHardwareFromSimpleConfig();
    // initHardwareFromIndividualConfigs();
    
    // Run hardware tests
    testHardware();
    
    // Setup expander GPIO
    setupExpanderGPIO();
    
    // Clear TFT
    if (tft) {
        tft->fillScreen(0x0000);
    }
    
    Serial.println("\nSetup complete!");
}

void loop() {
    static uint8_t ledState = 0;
    static int x = 0;
    
    // Read buttons
    uint16_t buttons = readExpanderButtons();
    if (buttons != 0) {
        Serial.print("Buttons pressed: 0x");
        Serial.println(buttons, HEX);
        
        // Toggle LEDs based on button press
        ledState ^= 0xFF;
        setExpanderLEDs(ledState);
    }
    
    // Check for touch
    if (touch) {
        uint16_t touchX, touchY;
        if (touch->getTouchPoint(&touchX, &touchY)) {
            Serial.print("Touch at: (");
            Serial.print(touchX);
            Serial.print(", ");
            Serial.print(touchY);
            Serial.println(")");
            
            // Draw a small circle at touch position
            if (tft) {
                for (int r = 0; r < 5; r++) {
                    for (int a = 0; a < 360; a += 15) {
                        float rad = a * PI / 180.0;
                        int px = touchX + (int)(r * cos(rad));
                        int py = touchY + (int)(r * sin(rad));
                        if (px >= 0 && px < tft->getWidth() && py >= 0 && py < tft->getHeight()) {
                            tft->drawPixel(px, py, 0xFFFF);
                        }
                    }
                }
            }
        }
    }
    
    // Simple animation
    if (tft) {
        tft->drawPixel(x, 100, 0xF800);  // Red dot
        x++;
        if (x >= tft->getWidth()) x = 0;
    }
    
    delay(10);
}
