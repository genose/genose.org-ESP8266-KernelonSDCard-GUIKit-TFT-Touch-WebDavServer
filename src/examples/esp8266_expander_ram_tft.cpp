// SPI SRAM (23LC1024) Driver
class SPISRAM {
    uint8_t csPin;
public:
    SPISRAM(uint8_t cs) : csPin(cs) {
        pinMode(csPin, OUTPUT);
        digitalWrite(csPin, HIGH);
    }
    
    void begin() {
        // SPI already initialized in main
        delay(10);
    }
    
    uint8_t read(uint32_t addr) {
        if (addr >= 131072) return 0;  // 128KB limit
        
        digitalWrite(csPin, LOW);
        SPI.transfer(0x03);  // READ command
        SPI.transfer((addr >> 16) & 0xFF);
        SPI.transfer((addr >> 8) & 0xFF);
        SPI.transfer(addr & 0xFF);
        uint8_t data = SPI.transfer(0);
        digitalWrite(csPin, HIGH);
        return data;
    }
    
    void write(uint32_t addr, uint8_t data) {
        if (addr >= 131072) return;  // 128KB limit
        
        digitalWrite(csPin, LOW);
        SPI.transfer(0x02);  // WRITE command
        SPI.transfer((addr >> 16) & 0xFF);
        SPI.transfer((addr >> 8) & 0xFF);
        SPI.transfer(addr & 0xFF);
        SPI.transfer(data);
        digitalWrite(csPin, HIGH);
        delayMicroseconds(1);  // Wait for write to complete
    }
    
    void readBuffer(uint32_t addr, uint8_t* buffer, size_t length) {
        if (addr + length > 131072) length = 131072 - addr;
        digitalWrite(csPin, LOW);
        SPI.transfer(0x03);
        SPI.transfer((addr >> 16) & 0xFF);
        SPI.transfer((addr >> 8) & 0xFF);
        SPI.transfer(addr & 0xFF);
        for (size_t i = 0; i < length; i++) {
            buffer[i] = SPI.transfer(0);
        }
        digitalWrite(csPin, HIGH);
    }
    
    void writeBuffer(uint32_t addr, const uint8_t* buffer, size_t length) {
        if (addr + length > 131072) length = 131072 - addr;
        digitalWrite(csPin, LOW);
        SPI.transfer(0x02);
        SPI.transfer((addr >> 16) & 0xFF);
        SPI.transfer((addr >> 8) & 0xFF);
        SPI.transfer(addr & 0xFF);
        for (size_t i = 0; i < length; i++) {
            SPI.transfer(buffer[i]);
        }
        digitalWrite(csPin, HIGH);
        delayMicroseconds(length);  // Wait for writes
    }
    
    size_t getSize() const { return 131072; }
};

// MCP23S17 GPIO Expander Driver
class MCP23S17 {
    uint8_t csPin;
    uint8_t irqPin;
public:
    MCP23S17(uint8_t cs, uint8_t irq = 255) : csPin(cs), irqPin(irq) {
        pinMode(csPin, OUTPUT);
        digitalWrite(csPin, HIGH);
        if (irqPin != 255) {
            pinMode(irqPin, INPUT_PULLUP);
        }
    }
    
    void begin() {
        // Initialize MCP23S17
        // Configure I/O direction, pull-ups, etc.
        writeRegister(0x00, 0x0000);  // IODIRA - all outputs
        writeRegister(0x01, 0x0000);  // IODIRB - all outputs
        writeRegister(0x0C, 0x0000);  // GPPUA - no pull-ups
        writeRegister(0x0D, 0x0000);  // GPPUB - no pull-ups
        delay(10);
    }
    
    void pinMode(uint8_t pin, uint8_t mode) {
        uint16_t reg = readRegister(pin < 8 ? 0x00 : 0x01);  // IODIRA or IODIRB
        if (mode == OUTPUT) {
            reg &= ~(1 << (pin % 8));
        } else {
            reg |= (1 << (pin % 8));
        }
        writeRegister(pin < 8 ? 0x00 : 0x01, reg);
    }
    
    void digitalWrite(uint8_t pin, uint8_t value) {
        uint16_t reg = readRegister(pin < 8 ? 0x12 : 0x13);  // GPIOA or GPIOB
        if (value == HIGH) {
            reg |= (1 << (pin % 8));
        } else {
            reg &= ~(1 << (pin % 8));
        }
        writeRegister(pin < 8 ? 0x12 : 0x13, reg);
    }
    
    uint8_t digitalRead(uint8_t pin) {
        uint16_t reg = readRegister(pin < 8 ? 0x12 : 0x13);  // GPIOA or GPIOB
        return (reg >> (pin % 8)) & 0x01;
    }
    
    void pullUp(uint8_t pin, bool enable) {
        uint16_t reg = readRegister(pin < 8 ? 0x0C : 0x0D);  // GPPUA or GPPUB
        if (enable) {
            reg |= (1 << (pin % 8));
        } else {
            reg &= ~(1 << (pin % 8));
        }
        writeRegister(pin < 8 ? 0x0C : 0x0D, reg);
    }
    
    bool getInterrupt() {
        if (irqPin == 255) return false;
        return digitalRead(irqPin) == LOW;
    }
    
private:
    uint16_t readRegister(uint8_t reg) {
        digitalWrite(csPin, LOW);
        SPI.transfer(0x41);  // Read register command
        SPI.transfer(reg);
        uint8_t low = SPI.transfer(0);
        uint8_t high = SPI.transfer(0);
        digitalWrite(csPin, HIGH);
        return (high << 8) | low;
    }
    
    void writeRegister(uint8_t reg, uint16_t value) {
        digitalWrite(csPin, LOW);
        SPI.transfer(0x40);  // Write register command
        SPI.transfer(reg);
        SPI.transfer(value & 0xFF);
        SPI.transfer((value >> 8) & 0xFF);
        digitalWrite(csPin, HIGH);
    }
};

// TFT ST7789 Driver (Simplified)
class TFT_ST7789 {
    uint8_t csPin;
    uint8_t dcPin;
    uint8_t rstPin;
    uint16_t width;
    uint16_t height;
public:
    TFT_ST7789(uint8_t cs, uint8_t dc, uint8_t rst, 
               uint16_t w = 320, uint16_t h = 240)
        : csPin(cs), dcPin(dc), rstPin(rst), width(w), height(h) {
        pinMode(csPin, OUTPUT);
        pinMode(dcPin, OUTPUT);
        if (rstPin != 255) {
            pinMode(rstPin, OUTPUT);
        }
        digitalWrite(csPin, HIGH);
        digitalWrite(dcPin, HIGH);
        if (rstPin != 255) {
            digitalWrite(rstPin, HIGH);
        }
    }
    
    void begin() {
        // Hardware reset
        if (rstPin != 255) {
            digitalWrite(rstPin, LOW);
            delay(10);
            digitalWrite(rstPin, HIGH);
            delay(100);
        }
        
        // Software reset
        sendCommand(0x01);
        delay(150);
        
        // Initialize display
        sendCommand(0x11);  // Sleep out
        delay(250);
        
        sendCommand(0x36);  // Memory Data Access Control
        sendData(0x00);     // Portrait orientation
        
        sendCommand(0x3A);  // COLMOD: Pixel Format Set
        sendData(0x05);     // 16-bit color
        
        sendCommand(0x21);  // Display Inversion On
        
        sendCommand(0x13);  // Normal Display Mode On
        delay(10);
        
        sendCommand(0x29);  // Display On
        delay(100);
        
        fillScreen(0x0000);  // Clear screen
    }
    
    void sendCommand(uint8_t cmd) {
        digitalWrite(csPin, LOW);
        digitalWrite(dcPin, LOW);
        SPI.transfer(cmd);
        digitalWrite(csPin, HIGH);
    }
    
    void sendData(uint8_t data) {
        digitalWrite(csPin, LOW);
        digitalWrite(dcPin, HIGH);
        SPI.transfer(data);
        digitalWrite(csPin, HIGH);
    }
    
    void write16(uint16_t data) {
        sendData(data >> 8);
        sendData(data & 0xFF);
    }
    
    void setAddrWindow(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1) {
        sendCommand(0x2A);  // Column Address Set
        write16(x0);
        write16(x1);
        
        sendCommand(0x2B);  // Row Address Set
        write16(y0);
        write16(y1);
        
        sendCommand(0x2C);  // Memory Write
    }
    
    void fillScreen(uint16_t color) {
        setAddrWindow(0, 0, width - 1, height - 1);
        digitalWrite(csPin, LOW);
        digitalWrite(dcPin, HIGH);
        for (uint32_t i = 0; i < (uint32_t)width * height; i++) {
            SPI.transfer(color >> 8);
            SPI.transfer(color & 0xFF);
        }
        digitalWrite(csPin, HIGH);
    }
    
    void drawPixel(int16_t x, int16_t y, uint16_t color) {
        if (x < 0 || x >= width || y < 0 || y >= height) return;
        
        setAddrWindow(x, y, x, y);
        digitalWrite(csPin, LOW);
        digitalWrite(dcPin, HIGH);
        SPI.transfer(color >> 8);
        SPI.transfer(color & 0xFF);
        digitalWrite(csPin, HIGH);
    }
    
    void drawRect(int16_t x, int16_t y, int16_t w, int16_t h, uint16_t color) {
        if (w <= 0 || h <= 0) return;
        
        setAddrWindow(x, y, x + w - 1, y + h - 1);
        digitalWrite(csPin, LOW);
        digitalWrite(dcPin, HIGH);
        for (int32_t i = 0; i < (int32_t)w * h; i++) {
            SPI.transfer(color >> 8);
            SPI.transfer(color & 0xFF);
        }
        digitalWrite(csPin, HIGH);
    }
    
    uint16_t getWidth() const { return width; }
    uint16_t getHeight() const { return height; }
};

