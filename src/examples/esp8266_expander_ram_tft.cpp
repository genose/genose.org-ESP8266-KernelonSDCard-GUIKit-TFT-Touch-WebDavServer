/**
 * Test all initialized hardware
 */
void testHardware() {
    if (sram) {
        Serial.println("Testing SRAM...");
        // Write test pattern
        sram->write(0, 0xAA);
        sram->write(1, 0x55);
        sram->write(2, 0x0F);
        sram->write(3, 0xF0);
        
        // Read back and verify
        if (sram->read(0) == 0xAA &&
            sram->read(1) == 0x55 &&
            sram->read(2) == 0x0F &&
            sram->read(3) == 0xF0) {
            Serial.println("  SRAM test: PASS");
        } else {
            Serial.println("  SRAM test: FAIL");
        }
    }
    
    if (expander) {
        Serial.println("Testing MCP23S17...");
        // Configure pin 0 as output
        expander->pinMode(0, OUTPUT);
        
        // Test writing HIGH
        expander->digitalWrite(0, HIGH);
        if (expander->digitalRead(0) == HIGH) {
            Serial.println("  Expander pin 0 write HIGH: PASS");
        } else {
            Serial.println("  Expander pin 0 write HIGH: FAIL");
        }
        
        // Test writing LOW
        expander->digitalWrite(0, LOW);
        if (expander->digitalRead(0) == LOW) {
            Serial.println("  Expander pin 0 write LOW: PASS");
        } else {
            Serial.println("  Expander pin 0 write LOW: FAIL");
        }
        
        // Configure pin 1 as input with pull-up
        expander->pinMode(1, INPUT);
        expander->pullUp(1, true);
        delay(1);
        if (expander->digitalRead(1) == HIGH) {
            Serial.println("  Expander pin 1 pull-up: PASS");
        } else {
            Serial.println("  Expander pin 1 pull-up: FAIL");
        }
    }
    
    if (touch) {
        Serial.println("Testing Touch Panel...");
        uint16_t x, y;
        if (touch->getTouchPoint(&x, &y)) {
            Serial.print("  Touch detected at: (");
            Serial.print(x);
            Serial.print(", ");
            Serial.print(y);
            Serial.println(") PASS");
        } else {
            Serial.println("  No touch detected (expected if not touching) - PASS");
        }
    }
    
    if (sdcard) {
        Serial.println("Testing SD Card...");
        uint8_t testBuffer[512] = {0};
        if (sdcard->readSector(0, testBuffer)) {
            Serial.println("  SD Card read sector 0: PASS");
        } else {
            Serial.println("  SD Card read sector 0: FAIL (card may not be formatted)");
        }
    }
    
    if (tft) {
        Serial.println("Testing TFT...");
        
        // Clear screen
        tft->fillScreen(0x0000);
        
        // Draw colored rectangles
        tft->drawRect(0, 0, 40, 40, 0xF800);    // Red
        tft->drawRect(40, 0, 40, 40, 0x07E0);   // Green
        tft->drawRect(80, 0, 40, 40, 0x001F);   // Blue
        
        // Draw a pixel
        tft->drawPixel(120, 20, 0xFFFF);       // White
        
        Serial.println("  TFT test: PASS (visual check required)");
    }
}

