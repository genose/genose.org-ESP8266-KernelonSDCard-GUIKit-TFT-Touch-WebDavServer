/**
 * Store data in external SRAM
 */
void storeInSRAM(uint32_t addr, const uint8_t* data, size_t length) {
    if (sram && addr + length <= sram->getSize()) {
        sram->writeBuffer(addr, data, length);
    }
}

/**
 * Retrieve data from external SRAM
 */
void retrieveFromSRAM(uint32_t addr, uint8_t* buffer, size_t length) {
    if (sram && addr + length <= sram->getSize()) {
        sram->readBuffer(addr, buffer, length);
    }
}

