class XPT2046_Touch {
    uint8_t csPin;
    uint8_t irqPin;
    uint16_t width;
    uint16_t height;
    bool touched;
    uint16_t touchX;
    uint16_t touchY;
public:
    XPT2046_Touch(uint8_t cs, uint8_t irq = 255, 
                  uint16_t w = 320, uint16_t h = 240)
        : csPin(cs), irqPin(irq), width(w), height(h), touched(false), touchX(0), touchY(0) {
        pinMode(csPin, OUTPUT);
        digitalWrite(csPin, HIGH);
        if (irqPin != 255) {
            pinMode(irqPin, INPUT_PULLUP);
        }
    }
    
    void begin() {
        delay(10);
    }
    
    // Read raw ADC values from touch controller
    uint16_t readRawX() {
        digitalWrite(csPin, LOW);
        SPI.transfer(0xD0);  // Channel Y- on X+ (for X position)
        uint8_t high = SPI.transfer(0);
        uint8_t low = SPI.transfer(0);
        digitalWrite(csPin, HIGH);
        return ((high << 8) | low) >> 3;  // 12-bit value
    }
    
    uint16_t readRawY() {
        digitalWrite(csPin, LOW);
        SPI.transfer(0x90);  // Channel X+ on Y- (for Y position)
        uint8_t high = SPI.transfer(0);
        uint8_t low = SPI.transfer(0);
        digitalWrite(csPin, HIGH);
        return ((high << 8) | low) >> 3;  // 12-bit value
    }
    
    // Check if touch is detected (using pen-down bit)
    bool isTouched() {
        digitalWrite(csPin, LOW);
        SPI.transfer(0xB0);  // Read Z1 and Z2 for touch detection
        uint8_t high = SPI.transfer(0);
        uint8_t low = SPI.transfer(0);
        digitalWrite(csPin, HIGH);
        
        // Check if touch is detected (pen-down bit in Z measurement)
        return ((high << 8) | low) > 0;
    }
    
    // Read calibrated touch coordinates
    bool getTouchPoint(uint16_t* x, uint16_t* y) {
        if (!isTouched()) {
            touched = false;
            return false;
        }
        
        // Read multiple samples and average
        uint32_t sumX = 0, sumY = 0;
        const int samples = 5;
        
        for (int i = 0; i < samples; i++) {
            sumX += readRawY();  // Note: X and Y are swapped in raw reading
            sumY += readRawX();
            delayMicroseconds(10);
        }
        
        // Calculate averages
        uint16_t rawX = sumY / samples;
        uint16_t rawY = sumX / samples;
        
        // Simple calibration - flip Y axis for TFT coordinate system
        touchX = (uint16_t)map(rawX, 0, 4095, 0, width - 1);
        touchY = (uint16_t)map(rawY, 0, 4095, height - 1, 0);
        
        *x = touchX;
        *y = touchY;
        touched = true;
        return true;
    }
    
    uint16_t getX() const { return touchX; }
    uint16_t getY() const { return touchY; }
    bool wasTouched() const { return touched; }
};

