/**
 * Example: Use expander GPIO for buttons
 */
void setupExpanderGPIO() {
    if (!expander) return;
    
    // Configure pins 0-7 as inputs with pull-ups (buttons)
    for (int i = 0; i < 8; i++) {
        expander->pinMode(i, INPUT);
        expander->pullUp(i, true);
    }
    
    // Configure pins 8-15 as outputs (LEDs)
    for (int i = 8; i < 16; i++) {
        expander->pinMode(i, OUTPUT);
        expander->digitalWrite(i, LOW);
    }
}

/**
 * Read button states from expander
 */
uint16_t readExpanderButtons() {
    if (!expander) return 0;
    
    uint16_t buttons = 0;
    for (int i = 0; i < 8; i++) {
        if (expander->digitalRead(i) == LOW) {  // Pressed (pull-up)
            buttons |= (1 << i);
        }
    }
    return buttons;
}

/**
 * Set LED states on expander
 */
void setExpanderLEDs(uint16_t ledStates) {
    if (!expander) return;
    
    for (int i = 8; i < 16; i++) {
        expander->digitalWrite(i, (ledStates >> (i - 8)) & 0x01);
    }
}

// ============================================================================
// Main Setup and Loop
// ============================================================================

void setup() {
    Serial.begin(115200);
    while (!Serial);
    
    Serial.println("ESP8266 + MCP23S17 + 23LC1024 + TFT Example");
    Serial.println("==========================================");
    
    // Choose one initialization method:
    // initHardwareFromUnionConfig();
    // initHardwareFromSimpleConfig();
    initHardwareFromIndividualConfigs();
    
    // Run hardware tests
    testHardware();
    
    // Setup expander GPIO
    setupExpanderGPIO();
    
    // Clear TFT
    if (tft) {
        tft->fillScreen(0x0000);
    }
    
    Serial.println("\nSetup complete!");
}

void loop() {
    static uint8_t ledState = 0;
    
    // Read buttons
    uint16_t buttons = readExpanderButtons();
    if (buttons != 0) {
        Serial.print("Buttons pressed: 0x");
        Serial.println(buttons, HEX);
        
        // Toggle LEDs based on button press
        ledState ^= 0xFF;
        setExpanderLEDs(ledState);
    }
    
    // Simple animation
    if (tft) {
        static int x = 0;
        tft->drawPixel(x, 100, 0xFFFF);
        x++;
        if (x >= tft->getWidth()) x = 0;
    }
    
    delay(10);
}
