/**
 * Initialize all hardware devices from the union-based configuration
 */
void initHardwareFromUnionConfig() {
    Serial.println("Initializing hardware from union config...");
    
    // Initialize SPI bus first
    SPI.begin();
    SPI.setFrequency(ESP8266_EXPANDER_RAM_TFT_CONFIG.max_speed_mhz * 1000000);
    SPI.setDataMode(SPI_MODE0);
    Serial.println("SPI bus initialized");
    
    // Initialize each device based on its type
    for (int i = 0; i < ESP8266_EXPANDER_RAM_TFT_CONFIG.bank_count; i++) {
        const guikit_device_bank_t* bank = &ESP8266_EXPANDER_RAM_TFT_CONFIG.banks[i];
        
        if (GUIKIT_BANK_IS_RAM(*bank)) {
            const guikit_ram_config_t* ram = guikit_bank_get_ram(bank);
            sram = new SPISRAM(ram->cs_pin);
            sram->begin();
            Serial.print("  SRAM initialized on CS=");
            Serial.print(ram->cs_pin);
            Serial.print(", Size: ");
            Serial.print(ram->size / 1024);
            Serial.println(" KB");
        }
        else if (GUIKIT_BANK_IS_SPI_EXPANDER(*bank)) {
            const guikit_spi_expander_config_t* exp = guikit_bank_get_spi_expander(bank);
            expander = new MCP23S17(exp->cs_pin, exp->irq_pin);
            expander->begin();
            Serial.print("  MCP23S17 initialized on CS=");
            Serial.println(exp->cs_pin);
        }
        else if (GUIKIT_BANK_IS_SPI_DEVICE(*bank)) {
            const guikit_spi_device_config_t* dev = guikit_bank_get_spi_device(bank);
            if (dev->type == GUIKIT_DEVICE_TFT) {
                tft = new TFT_ST7789(dev->cs_pin, TFT_DC_PIN, TFT_RST_PIN);
                tft->begin();
                Serial.print("  TFT initialized on CS=");
                Serial.println(dev->cs_pin);
            }
        }
    }
    
    Serial.println("All hardware initialized successfully");
}

