/// @brief Read a 32-bit value from buffer (big-endian)
static uint32_t read_be32(const uint8_t* data) {
    return (data[0] << 24) | (data[1] << 16) | (data[2] << 8) | data[3];
}

/// @brief Read a 16-bit value from buffer (big-endian)
static uint16_t read_be16(const uint8_t* data) {
    return (data[0] << 8) | data[1];
}

/// @brief Calculate CRC32 for a chunk
static uint32_t png_chunk_crc(const uint8_t* type, const uint8_t* data, uint32_t length) {
    uint32_t crc = 0xFFFFFFFF;
    
    // CRC of type
    for (int i = 0; i < 4; i++) {
        crc = crc32_table[(crc ^ type[i]) & 0xFF] ^ (crc >> 8);
    }
    
    // CRC of data
    for (uint32_t i = 0; i < length; i++) {
        crc = crc32_table[(crc ^ data[i]) & 0xFF] ^ (crc >> 8);
    }
    
    return crc ^ 0xFFFFFFFF;
}

