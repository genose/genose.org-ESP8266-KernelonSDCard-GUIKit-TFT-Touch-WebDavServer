bool png_is_valid_file(const char* path) {
    if (!path || !sd_file_exists(path)) {
        g_last_error = PNG_ERR_FILE_NOT_FOUND;
        return false;
    }
    
    uint8_t signature[8];
    if (!sd_read_file(path, signature, 0, 8)) {
        g_last_error = PNG_ERR_SD_CARD_ERROR;
        return false;
    }
    
    if (memcmp(signature, PNG_SIGNATURE, 8) != 0) {
        g_last_error = PNG_ERR_INVALID_PNG;
        return false;
    }
    
    return true;
}

