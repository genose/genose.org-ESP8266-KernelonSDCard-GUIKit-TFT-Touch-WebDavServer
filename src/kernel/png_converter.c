bool png_get_dimensions(const char* path, uint16_t* width, uint16_t* height) {
    if (!path || !width || !height) {
        g_last_error = PNG_ERR_INVALID_PNG;
        return false;
    }
    
    if (!png_is_valid_file(path)) {
        return false;
    }
    
    // Skip signature (8 bytes)
    uint8_t chunk_header[8];  // Length (4) + Type (4)
    
    // Read first chunk header (should be IHDR)
    if (!sd_read_file(path, chunk_header, 8, 8)) {
        g_last_error = PNG_ERR_SD_CARD_ERROR;
        return false;
    }
    
    uint32_t chunk_length = read_be32(chunk_header);
    uint32_t chunk_type = read_be32(chunk_header + 4);
    
    if (chunk_type != PNG_CHUNK_IHDR) {
        g_last_error = PNG_ERR_INVALID_PNG;
        return false;
    }
    
    // Read IHDR data (13 bytes)
    uint8_t ihdr_data[13];
    if (!sd_read_file(path, ihdr_data, 16, 13)) {
        g_last_error = PNG_ERR_SD_CARD_ERROR;
        return false;
    }
    
    *width = read_be32(ihdr_data);
    *height = read_be32(ihdr_data + 4);
    
    // Validate dimensions
    if (*width == 0 || *height == 0) {
        g_last_error = PNG_ERR_INVALID_PNG;
        return false;
    }
    
    if (*width > PNG_CONVERTER_MAX_WIDTH || *height > PNG_CONVERTER_MAX_HEIGHT) {
        g_last_error = PNG_ERR_TOO_LARGE;
        return false;
    }
    
    return true;
}

