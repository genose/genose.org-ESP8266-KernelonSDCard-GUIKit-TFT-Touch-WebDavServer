bool png_save_results(const PngRgbHeader* header, 
                     const uint8_t* rgb_data, 
                     uint32_t rgb_size) {
    if (!header || !rgb_data || rgb_size == 0) {
        g_last_error = PNG_ERR_INVALID_PNG;
        return false;
    }
    
    // Save header
    if (!sd_write_file(PNG_CONVERTER_DEFAULT_HEADER, header, sizeof(PngRgbHeader))) {
        g_last_error = PNG_ERR_SD_CARD_ERROR;
        return false;
    }
    
    // Save RGB data
    if (!sd_write_file(PNG_CONVERTER_DEFAULT_OUTPUT, rgb_data, rgb_size)) {
        g_last_error = PNG_ERR_SD_CARD_ERROR;
        return false;
    }
    
    g_last_error = PNG_ERR_NONE;
    return true;
}

