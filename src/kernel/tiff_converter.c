bool tiff_converter_run(const char* tiff_path) {
    const char* input_path = tiff_path ? tiff_path : TIFF_CONVERTER_DEFAULT_INPUT;
    
    printf("[TIFF_CONVERTER] Starting conversion\n");
    printf("[TIFF_CONVERTER] Input: %s\n", input_path);
    
    // Validate TIFF file
    task_progress_minimal("Validating TIFF", 0);
    if (!tiff_is_valid_file(input_path)) {
        printf("[TIFF_CONVERTER] ERROR: %s\n", tiff_converter_error_to_string(g_last_error));
        task_progress_minimal_clear();
        return false;
    }
    task_progress_minimal("Validating TIFF", 50);
    
    // Get dimensions
    uint16_t width, height;
    if (!tiff_get_dimensions(input_path, &width, &height)) {
        printf("[TIFF_CONVERTER] ERROR: %s\n", tiff_converter_error_to_string(g_last_error));
        task_progress_minimal_clear();
        return false;
    }
    task_progress_minimal("Validating TIFF", 100);
    
    printf("[TIFF_CONVERTER] Image: %ux%u\n", width, height);
    
    // Calculate required buffer size
    uint32_t bytes_per_pixel = 3;  // RGB888
    uint32_t required_size = width * height * bytes_per_pixel;
    
    // Allocate buffer
    task_progress_minimal("Allocating memory", 0);
    uint8_t* rgb_buffer = (uint8_t*)malloc(required_size);
    if (!rgb_buffer) {
        g_last_error = TIFF_ERR_MEMORY_ERROR;
        printf("[TIFF_CONVERTER] ERROR: Failed to allocate %u bytes\n", required_size);
        task_progress_minimal_clear();
        return false;
    }
    task_progress_minimal("Allocating memory", 100);
    
    // Decode TIFF to RGB
    task_progress_minimal("Decoding TIFF", 0);
    TiffRgbHeader header;
    uint8_t* rgb_data = tiff_decode_to_rgb(input_path, &header, rgb_buffer, required_size);
    
    if (!rgb_data) {
        printf("[TIFF_CONVERTER] ERROR: %s\n", tiff_converter_error_to_string(g_last_error));
        free(rgb_buffer);
        return false;
    }
    
    printf("[TIFF_CONVERTER] Decoded to RGB: %u bytes\n", header.data_size);
    printf("[TIFF_CONVERTER] CRC32: %08lX\n", header.crc32);
    
    // Save results for parent task
    task_progress_minimal("Saving results", 0);
    if (!tiff_save_results(&header, rgb_data, header.data_size)) {
        printf("[TIFF_CONVERTER] ERROR: Failed to save results\n");
        task_progress_minimal_clear();
        free(rgb_buffer);
        return false;
    }
    task_progress_minimal("Saving results", 100);
    
    printf("[TIFF_CONVERTER] Results saved to SD card\n");
    printf("[TIFF_CONVERTER] Header: %s\n", TIFF_CONVERTER_DEFAULT_HEADER);
    printf("[TIFF_CONVERTER] RGB: %s\n", TIFF_CONVERTER_DEFAULT_OUTPUT);
    
    free(rgb_buffer);
    return true;
}

