bool tiff_save_results(const TiffRgbHeader* header, 
                     const uint8_t* rgb_data, 
                     uint32_t rgb_size) {
    if (!header || !rgb_data || rgb_size == 0) {
        g_last_error = TIFF_ERR_INVALID_TIFF;
        return false;
    }
    
    // Save header
    if (!sd_write_file(TIFF_CONVERTER_DEFAULT_HEADER, header, sizeof(TiffRgbHeader))) {
        g_last_error = TIFF_ERR_SD_CARD_ERROR;
        return false;
    }
    
    // Save RGB data
    if (!sd_write_file(TIFF_CONVERTER_DEFAULT_OUTPUT, rgb_data, rgb_size)) {
        g_last_error = TIFF_ERR_SD_CARD_ERROR;
        return false;
    }
    
    g_last_error = TIFF_ERR_NONE;
    return true;
}

