bool tiff_is_valid_file(const char* path) {
    if (!path || !sd_file_exists(path)) {
        g_last_error = TIFF_ERR_FILE_NOT_FOUND;
        return false;
    }
    
    uint8_t header[8];
    if (!sd_read_file(path, header, 0, 8)) {
        g_last_error = TIFF_ERR_SD_CARD_ERROR;
        return false;
    }
    
    // Check byte order
    uint16_t byte_order = read_be16(header);
    if (byte_order == TIFF_BIG_ENDIAN) {
        g_is_big_endian = true;
    } else if (byte_order == TIFF_LITTLE_ENDIAN) {
        g_is_big_endian = false;
    } else {
        g_last_error = TIFF_ERR_INVALID_TIFF;
        return false;
    }
    
    // Check version (always 42)
    uint16_t version = read_uint16(header + 2);
    if (version != TIFF_VERSION) {
        g_last_error = TIFF_ERR_INVALID_TIFF;
        return false;
    }
    
    // Check magic number (offset to IFD, usually 8)
    uint32_t ifd_offset = read_uint32(header + 4);
    if (ifd_offset == 0) {
        g_last_error = TIFF_ERR_INVALID_TIFF;
        return false;
    }
    
    return true;
}

// ============================================================================
// TIFF DIMENSIONS PARSING (from IFD)
// ============================================================================

bool tiff_get_dimensions(const char* path, uint16_t* width, uint16_t* height) {
    if (!path || !width || !height) {
        g_last_error = TIFF_ERR_INVALID_TIFF;
        return false;
    }
    
    if (!tiff_is_valid_file(path)) {
        return false;
    }
    
    // Read file header
    uint8_t header[8];
    if (!sd_read_file(path, header, 0, 8)) {
        g_last_error = TIFF_ERR_SD_CARD_ERROR;
        return false;
    }
    
    // Get IFD offset from header
    uint32_t ifd_offset = read_uint32(header + 4);
    
    // Read IFD (Image File Directory)
    uint8_t ifd[512];  // Enough for typical IFD
    if (!sd_read_file(path, ifd, ifd_offset, sizeof(ifd))) {
        g_last_error = TIFF_ERR_SD_CARD_ERROR;
        return false;
    }
    
    // Read number of directory entries
    uint16_t num_entries = read_uint16(ifd);
    
    // Parse IFD entries
    uint32_t offset = 2;  // Skip entry count
    
    for (uint16_t i = 0; i < num_entries; i++) {
        if (offset + 12 > sizeof(ifd)) break;
        
        uint16_t tag = read_uint16(ifd + offset);
        uint16_t type = read_uint16(ifd + offset + 2);
        uint32_t count = read_uint32(ifd + offset + 4);
        uint32_t value_offset = read_uint32(ifd + offset + 8);
        
        offset += 12;
        
        switch (tag) {
            case TIFF_TAG_IMAGE_WIDTH:
                if (type == 3 || type == 4) {  // SHORT or LONG
                    *width = (uint16_t)value_offset;
                }
                break;
            
            case TIFF_TAG_IMAGE_LENGTH:
                if (type == 3 || type == 4) {  // SHORT or LONG
                    *height = (uint16_t)value_offset;
                }
                break;
        }
    }
    
    // Validate dimensions
    if (*width == 0 || *height == 0) {
        g_last_error = TIFF_ERR_INVALID_TIFF;
        return false;
    }
    
    if (*width > TIFF_CONVERTER_MAX_WIDTH || *height > TIFF_CONVERTER_MAX_HEIGHT) {
        g_last_error = TIFF_ERR_TOO_LARGE;
        return false;
    }
    
    return true;
}

