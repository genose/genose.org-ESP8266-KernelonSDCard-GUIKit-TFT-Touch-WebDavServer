bool jpeg_converter_run(const char* jpeg_path) {
    const char* input_path = jpeg_path ? jpeg_path : JPEG_CONVERTER_DEFAULT_INPUT;
    
    printf("[JPEG_CONVERTER] Starting conversion\n");
    printf("[JPEG_CONVERTER] Input: %s\n", input_path);
    
    // Validate JPEG file
    task_progress_minimal("Validating JPEG", 0);
    if (!jpeg_is_valid_file(input_path)) {
        printf("[JPEG_CONVERTER] ERROR: %s\n", jpeg_converter_error_to_string(g_last_error));
        task_progress_minimal_clear();
        return false;
    }
    task_progress_minimal("Validating JPEG", 50);
    
    // Get dimensions
    uint16_t width, height;
    if (!jpeg_get_dimensions(input_path, &width, &height)) {
        printf("[JPEG_CONVERTER] ERROR: %s\n", jpeg_converter_error_to_string(g_last_error));
        task_progress_minimal_clear();
        return false;
    }
    task_progress_minimal("Validating JPEG", 100);
    
    printf("[JPEG_CONVERTER] Image: %ux%u\n", width, height);
    
    // Calculate required buffer size
    uint32_t bytes_per_pixel = 3;  // RGB888
    uint32_t required_size = width * height * bytes_per_pixel;
    
    // Allocate buffer
    task_progress_minimal("Allocating memory", 0);
    uint8_t* rgb_buffer = (uint8_t*)malloc(required_size);
    if (!rgb_buffer) {
        g_last_error = JPEG_ERR_MEMORY_ERROR;
        printf("[JPEG_CONVERTER] ERROR: Failed to allocate %u bytes\n", required_size);
        task_progress_minimal_clear();
        return false;
    }
    task_progress_minimal("Allocating memory", 100);
    
    // Decode JPEG to RGB
    task_progress_minimal("Decoding JPEG", 0);
    JpegRgbHeader header;
    uint8_t* rgb_data = jpeg_decode_to_rgb(input_path, &header, rgb_buffer, required_size);
    
    if (!rgb_data) {
        printf("[JPEG_CONVERTER] ERROR: %s\n", jpeg_converter_error_to_string(g_last_error));
        free(rgb_buffer);
        return false;
    }
    
    printf("[JPEG_CONVERTER] Decoded to RGB: %u bytes\n", header.data_size);
    printf("[JPEG_CONVERTER] CRC32: %08lX\n", header.crc32);
    
    // Save results for parent task
    task_progress_minimal("Saving results", 0);
    if (!jpeg_save_results(&header, rgb_data, header.data_size)) {
        printf("[JPEG_CONVERTER] ERROR: Failed to save results\n");
        task_progress_minimal_clear();
        free(rgb_buffer);
        return false;
    }
    task_progress_minimal("Saving results", 100);
    
    printf("[JPEG_CONVERTER] Results saved to SD card\n");
    printf("[JPEG_CONVERTER] Header: %s\n", JPEG_CONVERTER_DEFAULT_HEADER);
    printf("[JPEG_CONVERTER] RGB: %s\n", JPEG_CONVERTER_DEFAULT_OUTPUT);
    
    free(rgb_buffer);
    return true;
}

