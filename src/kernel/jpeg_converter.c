/// @brief Read a 16-bit value from buffer (big-endian)
static uint16_t read_be16(const uint8_t* data) {
    return (data[0] << 8) | data[1];
}

/// @brief Read a 32-bit value from buffer (big-endian)
static uint32_t read_be32(const uint8_t* data) {
    return (data[0] << 24) | (data[1] << 16) | (data[2] << 8) | data[3];
}

/// @brief Skip to next marker in JPEG stream
/// @param data JPEG data
/// @param offset Current offset
/// @param size Total size
/// @return New offset at marker, or -1 on error
static int32_t find_next_marker(const uint8_t* data, uint32_t offset, uint32_t size) {
    if (offset + 2 > size) return -1;
    
    // Check if we're already at a marker
    if (data[offset] == 0xFF && data[offset + 1] != 0x00 && data[offset + 1] != 0xFF) {
        return offset;
    }
    
    // Skip to next FF marker
    for (uint32_t i = offset + 2; i < size - 1; i++) {
        if (data[i] == 0xFF && data[i + 1] != 0x00 && data[i + 1] != 0xFF) {
            return i;
        }
    }
    
    return -1;
}

/// @brief Get marker type from 16-bit marker value
/// @param marker 16-bit marker value
/// @return Marker type constant
static uint16_t get_marker_type(uint16_t marker) {
    return marker & 0xFF;
}

