// JPEG DIMENSIONS PARSING (from SOF0 marker)
// ============================================================================

bool jpeg_get_dimensions(const char* path, uint16_t* width, uint16_t* height) {
    if (!path || !width || !height) {
        g_last_error = JPEG_ERR_INVALID_JPEG;
        return false;
    }
    
    if (!jpeg_is_valid_file(path)) {
        return false;
    }
    
    // Read file into buffer for parsing
    // In real implementation, use streaming read
    uint8_t buffer[4096];  // Enough for header
    uint32_t bytes_read = 0;
    
    if (!sd_read_file(path, buffer, 0, sizeof(buffer))) {
        g_last_error = JPEG_ERR_SD_CARD_ERROR;
        return false;
    }
    
    uint32_t offset = 2;  // Skip SOI marker
    
    while (offset < sizeof(buffer) - 10) {
        int32_t marker_offset = find_next_marker(buffer, offset, sizeof(buffer));
        if (marker_offset < 0) break;
        
        offset = marker_offset;
        uint16_t marker = read_be16(buffer + offset);
        uint16_t marker_type = get_marker_type(marker);
        
        // Check for SOF0 (Baseline DCT) marker
        if (marker == JPEG_MARKER_SOF0 || marker == JPEG_MARKER_SOF2) {
            // Skip marker (2 bytes)
            offset += 2;
            
            // Get segment length (2 bytes, includes length field itself)
            uint16_t segment_length = read_be16(buffer + offset);
            offset += 2;
            
            // Read precision (1 byte) - skip
            uint8_t precision = buffer[offset++];
            (void)precision;
            
            // Read height (2 bytes)
            *height = read_be16(buffer + offset);
            offset += 2;
            
            // Read width (2 bytes)
            *width = read_be16(buffer + offset);
            offset += 2;
            
            // Validate dimensions
            if (*width == 0 || *height == 0) {
                g_last_error = JPEG_ERR_INVALID_JPEG;
                return false;
            }
            
            if (*width > JPEG_CONVERTER_MAX_WIDTH || *height > JPEG_CONVERTER_MAX_HEIGHT) {
                g_last_error = JPEG_ERR_TOO_LARGE;
                return false;
            }
            
            return true;
        }
        
        // Skip to next marker
        if (marker_type == 0x00) {
            offset++;
        } else {
            // Get segment length
            uint16_t segment_length = read_be16(buffer + offset + 2);
            offset += segment_length;
        }
    }
    
    g_last_error = JPEG_ERR_INVALID_JPEG;
    return false;
}

