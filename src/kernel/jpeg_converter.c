/**
 * @brief Load conversion results in GUI (Task A)
 * 
 * Call this after task_restore() to check if conversion completed.
 * 
 * @param header Pointer to header struct
 * @param rgb_buffer Buffer for RGB data
 * @param buffer_size Size of buffer
 * @return Number of bytes loaded, or 0 on error
 */
uint32_t gui_load_jpeg_conversion_results(JpegRgbHeader* header, 
                                          uint8_t* rgb_buffer, 
                                          uint32_t buffer_size) {
    if (!header || !rgb_buffer || buffer_size == 0) {
        return 0;
    }
    
    // Check if results exist
    if (!task_child_has_file("converted_jpeg.hdr")) {
        printf("[GUI] No JPEG conversion results found\n");
        return 0;
    }
    
    printf("[GUI] Loading JPEG conversion results...\n");
    
    // Load header
    uint32_t header_size = sizeof(JpegRgbHeader);
    uint32_t bytes_read = task_load_from_child("converted_jpeg.hdr", header, header_size);
    
    if (bytes_read != header_size) {
        printf("[GUI] ERROR: Failed to load header\n");
        return 0;
    }
    
    // Validate header
    if (header->bits_per_pixel != 24) {
        printf("[GUI] ERROR: Unsupported BPP: %u\n", header->bits_per_pixel);
        return 0;
    }
    
    // Load RGB data
    uint32_t data_to_read = (header->data_size < buffer_size) ? 
                            header->data_size : buffer_size;
    
    bytes_read = task_load_from_child("converted_jpeg.rgb", rgb_buffer, data_to_read);
    
    if (bytes_read == 0) {
        printf("[GUI] ERROR: Failed to load RGB data\n");
        return 0;
    }
    
    // Verify CRC32
    if (header->crc32 != 0) {
        uint32_t calculated_crc = crc32(0xFFFFFFFF, rgb_buffer, bytes_read) ^ 0xFFFFFFFF;
        if (calculated_crc != header->crc32) {
            printf("[GUI] WARNING: CRC32 mismatch!\n");
        }
    }
    
    printf("[GUI] Loaded %u bytes of RGB data (%ux%u, %u bpp)\n", 
           bytes_read, header->width, header->height, header->bits_per_pixel);
    
    return bytes_read;
}
