bool jpeg_save_results(const JpegRgbHeader* header, 
                     const uint8_t* rgb_data, 
                     uint32_t rgb_size) {
    if (!header || !rgb_data || rgb_size == 0) {
        g_last_error = JPEG_ERR_INVALID_JPEG;
        return false;
    }
    
    // Save header
    if (!sd_write_file(JPEG_CONVERTER_DEFAULT_HEADER, header, sizeof(JpegRgbHeader))) {
        g_last_error = JPEG_ERR_SD_CARD_ERROR;
        return false;
    }
    
    // Save RGB data
    if (!sd_write_file(JPEG_CONVERTER_DEFAULT_OUTPUT, rgb_data, rgb_size)) {
        g_last_error = JPEG_ERR_SD_CARD_ERROR;
        return false;
    }
    
    g_last_error = JPEG_ERR_NONE;
    return true;
}

