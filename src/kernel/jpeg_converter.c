uint8_t* jpeg_decode_to_rgb(const char* jpeg_path, 
                           JpegRgbHeader* header, 
                           uint8_t* rgb_buffer, 
                           uint32_t buffer_size) {
    if (!jpeg_path || !header) {
        g_last_error = JPEG_ERR_INVALID_JPEG;
        return NULL;
    }
    
    // Get dimensions
    uint16_t width, height;
    if (!jpeg_get_dimensions(jpeg_path, &width, &height)) {
        return NULL;
    }
    
    // For demo: assume RGB888 (24-bit)
    uint8_t bpp = 24;
    uint32_t bytes_per_pixel = bpp / 8;
    uint32_t required_size = width * height * bytes_per_pixel;
    
    if (required_size > buffer_size) {
        g_last_error = JPEG_ERR_MEMORY_ERROR;
        return NULL;
    }
    
    // Fill header
    header->width = width;
    header->height = height;
    header->bits_per_pixel = bpp;
    header->data_size = required_size;
    memset(header->reserved, 0, sizeof(header->reserved));
    
    // For demo purposes: create a gradient pattern
    // In real implementation, this would be actual JPEG decoding
    
    // Calculate total pixels for progress
    uint32_t total_pixels = width * height;
    uint32_t pixels_processed = 0;
    uint8_t last_percent = 0;
    
    for (uint32_t y = 0; y < height; y++) {
        for (uint32_t x = 0; x < width; x++) {
            uint32_t idx = (y * width + x) * bytes_per_pixel;
            
            // Create a gradient based on position
            // JPEG uses YCbCr color space, but we output RGB for simplicity
            uint8_t r = (uint8_t)((x * 255) / width);
            uint8_t g = (uint8_t)((y * 255) / height);
            uint8_t b = (uint8_t)(((x + y) * 255) / (width + height));
            
            if (idx + 2 < buffer_size) {
                rgb_buffer[idx] = r;
                rgb_buffer[idx + 1] = g;
                rgb_buffer[idx + 2] = b;
            }
            
            // Update progress display every ~1%
            pixels_processed++;
            if (total_pixels > 0) {
                uint8_t current_percent = (uint8_t)((pixels_processed * 100) / total_pixels);
                if (current_percent != last_percent) {
                    last_percent = current_percent;
                    // Use minimal progress display - no heap allocation
                    task_progress_minimal("Decoding JPEG", current_percent);
                }
            }
        }
    }
    
    // Clear progress when done
    task_progress_minimal_clear();
    
    // Calculate CRC32
    header->crc32 = crc32(0xFFFFFFFF, rgb_buffer, required_size) ^ 0xFFFFFFFF;
    
    g_last_error = JPEG_ERR_NONE;
    return rgb_buffer;
}

