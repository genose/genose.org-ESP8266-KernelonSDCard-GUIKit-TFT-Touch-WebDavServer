bool jpeg_is_valid_file(const char* path) {
    if (!path || !sd_file_exists(path)) {
        g_last_error = JPEG_ERR_FILE_NOT_FOUND;
        return false;
    }
    
    uint8_t signature[2];
    if (!sd_read_file(path, signature, 0, 2)) {
        g_last_error = JPEG_ERR_SD_CARD_ERROR;
        return false;
    }
    
    if (memcmp(signature, JPEG_SOI, 2) != 0) {
        g_last_error = JPEG_ERR_INVALID_JPEG;
        return false;
    }
    
    return true;
}

