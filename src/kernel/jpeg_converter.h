/**
 * @file jpeg_converter.h
 * @brief JPEG to RGB Converter Task for GUIKit
 * 
 * This is a heavy task (Task B) that:
 * 1. Loads JPEG file from SD card
 * 2. Decodes JPEG to RGB format
 * 3. Saves RGB data to SD card for parent task to use
 * 4. Returns control to parent via task_restore()
 * 
 * This task is designed to be loaded by the task switcher:
 *   Task A (GUI) -> task_switch_to("/kernel/jpeg_converter.bin") -> Task B
 *   Task B runs, does conversion, user clicks Back -> task_restore() -> Task A
 * 
 * Communication:
 *   Input:  JPEG file path set by Task A (via command line or config)
 *   Output: RGB data saved to /tmp/task_comm/converted_jpeg.rgb
 *           Header saved to /tmp/task_comm/converted_jpeg.hdr
 * 
 * Generated by Mistral Vibe
 * Date: 2026-08-16
 */

#ifndef JPEG_CONVERTER_H
#define JPEG_CONVERTER_H

#include <stdint.h>
#include <stdbool.h>

// ============================================================================
// RGB IMAGE HEADER (for communication with parent task)
// ============================================================================

/// @brief RGB image header structure for parent task communication
/// @note Must match the PngRgbHeader in png_converter.h for consistency
typedef struct {
    uint16_t width;            ///< Image width in pixels
    uint16_t height;           ///< Image height in pixels
    uint8_t bits_per_pixel;    ///< Bits per pixel (24 for RGB888)
    uint32_t data_size;        ///< Size of RGB data in bytes
    uint32_t crc32;            ///< CRC32 checksum of RGB data
    uint8_t reserved[16];      ///< Reserved for future use
} JpegRgbHeader;

// ============================================================================
// CONFIGURATION
// ============================================================================

/// @brief Default input JPEG path
#define JPEG_CONVERTER_DEFAULT_INPUT "/images/input.jpg"

/// @brief Default output RGB path
#define JPEG_CONVERTER_DEFAULT_OUTPUT "/tmp/task_comm/converted_jpeg.rgb"

/// @brief Default output header path
#define JPEG_CONVERTER_DEFAULT_HEADER "/tmp/task_comm/converted_jpeg.hdr"

/// @brief Max image dimensions
#define JPEG_CONVERTER_MAX_WIDTH 1024
#define JPEG_CONVERTER_MAX_HEIGHT 768

// ============================================================================
// ERROR CODES
// ============================================================================

/// @brief JPEG converter error codes
typedef enum {
    JPEG_ERR_NONE = 0,
    JPEG_ERR_FILE_NOT_FOUND,
    JPEG_ERR_INVALID_JPEG,
    JPEG_ERR_UNSUPPORTED_FORMAT,
    JPEG_ERR_MEMORY_ERROR,
    JPEG_ERR_SD_CARD_ERROR,
    JPEG_ERR_TOO_LARGE
} JpegConverterError;

// ============================================================================
// MAIN FUNCTIONS
// ============================================================================

/**
 * @brief Main entry point for JPEG converter task
 * 
 * This function:
 * 1. Initializes task switcher
 * 2. Checks if launched from parent task
 * 3. Loads JPEG file
 * 4. Converts to RGB
 * 5. Saves results
 * 6. Waits for back button or auto-return
 * 
 * @param jpeg_path Path to input JPEG file (NULL for default)
 * @return true on success
 */
bool jpeg_converter_run(const char* jpeg_path);

/**
 * @brief Decode JPEG file to RGB
 * 
 * @param jpeg_path Path to JPEG file
 * @param header Pointer to header struct to fill
 * @param rgb_buffer Buffer to store RGB data (allocated by caller)
 * @param buffer_size Size of buffer
 * @return Pointer to RGB data, or NULL on error
 */
uint8_t* jpeg_decode_to_rgb(const char* jpeg_path, 
                           JpegRgbHeader* header, 
                           uint8_t* rgb_buffer, 
                           uint32_t buffer_size);

/**
 * @brief Get last error
 * 
 * @return Last error code
 */
JpegConverterError jpeg_converter_get_error(void);

/**
 * @brief Get error message string
 * 
 * @param error Error code
 * @return Human-readable error message
 */
const char* jpeg_converter_error_to_string(JpegConverterError error);

// ============================================================================
// UTILITY FUNCTIONS
// ============================================================================

/**
 * @brief Check if JPEG file is valid
 * 
 * @param path Path to JPEG file
 * @return true if valid JPEG
 */
bool jpeg_is_valid_file(const char* path);

/**
 * @brief Get JPEG file dimensions without full decode
 * 
 * @param path Path to JPEG file
 * @param width Output: width in pixels
 * @param height Output: height in pixels
 * @return true on success
 */
bool jpeg_get_dimensions(const char* path, uint16_t* width, uint16_t* height);

/**
 * @brief Save RGB data for parent task
 * 
 * @param header Image header
 * @param rgb_data RGB pixel data
 * @param rgb_size Size of RGB data
 * @return true on success
 */
bool jpeg_save_results(const JpegRgbHeader* header, 
                     const uint8_t* rgb_data, 
                     uint32_t rgb_size);

// ============================================================================
// STANDALONE TASK ENTRY POINT
// ============================================================================

/**
 * @brief Standalone entry point when compiled as separate kernel
 * 
 * This is the main() equivalent for the JPEG converter task.
 * It initializes everything and runs the converter.
 */
void jpeg_converter_task_main(void);

#endif // JPEG_CONVERTER_H
