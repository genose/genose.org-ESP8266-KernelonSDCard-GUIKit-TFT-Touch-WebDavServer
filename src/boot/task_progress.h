/**
 * @file task_progress.h
 * @brief Progress Display Utilities for Heavy Tasks
 * 
 * Lightweight progress display on TFT for heavy tasks running with low RAM.
 * Designed to use minimal RAM (< 1KB) and work when only 10KB is available.
 * 
 * Features:
 * - Text-based progress (e.g., "Converting: 45%")
 * - Optional progress bar
 * - Automatic TFT initialization if not already done
 * - Non-blocking updates
 * 
 * Usage:
 *   task_progress_init();  // In task setup
 *   task_progress_show("Processing", 0, 100);  // Start
 *   for (i=0; i<100; i++) {
 *       do_work();
 *       task_progress_update(i+1);  // Update to i+1%
 *   }
 *   task_progress_done();  // Clean up
 * 
 * Generated by Mistral Vibe
 * Date: 2026-08-16
 */

#ifndef TASK_PROGRESS_H
#define TASK_PROGRESS_H

#include <stdint.h>
#include <stdbool.h>

// ============================================================================
// CONFIGURATION
// ============================================================================

/// @brief Default position for progress text
#define PROGRESS_X 10
#define PROGRESS_Y 200

/// @brief Default position for progress bar
#define PROGRESS_BAR_X 10
#define PROGRESS_BAR_Y 220
#define PROGRESS_BAR_WIDTH 300
#define PROGRESS_BAR_HEIGHT 20

/// @brief Colors (16-bit RGB565)
#define PROGRESS_BG_COLOR 0x0000  // Black
#define PROGRESS_TEXT_COLOR 0xFFFF // White
#define PROGRESS_BAR_COLOR 0x07E0  // Green
#define PROGRESS_BAR_BG 0x18E3     // Dark gray

// ============================================================================
// PROGRESS STATE (minimal RAM usage)
// ============================================================================

/// @brief Progress display state (uses only 32 bytes)
typedef struct {
    bool active;             ///< Is progress display active
    bool show_bar;           ///< Show progress bar
    bool show_text;          ///< Show text percentage
    int16_t x;               ///< Text X position
    int16_t y;               ///< Text Y position
    int16_t bar_x;           ///< Bar X position
    int16_t bar_y;           ///< Bar Y position
    uint16_t bar_width;      ///< Bar width
    uint16_t bar_height;     ///< Bar height
    uint16_t fg_color;       ///< Foreground color
    uint16_t bg_color;       ///< Background color
    uint16_t text_color;     ///< Text color
    uint8_t current_percent; ///< Current percentage (0-100)
    uint8_t max_percent;     ///< Maximum percentage
    char message[32];       ///< Status message
} TaskProgressState;

// ============================================================================
// GLOBAL STATE (single instance, shared across all tasks)
// ============================================================================

/// @brief Get the global progress state (allocated on demand)
TaskProgressState* task_progress_get_state(void);

// ============================================================================
// INITIALIZATION
// ============================================================================

/**
 * @brief Initialize progress display
 * 
 * @param show_bar Show progress bar (uses more RAM)
 * @param show_text Show text percentage
 */
void task_progress_init(bool show_bar, bool show_text);

/**
 * @brief Initialize with custom position
 * 
 * @param x Text X position
 * @param y Text Y position
 * @param bar_x Bar X position (if show_bar=true)
 * @param bar_y Bar Y position (if show_bar=true)
 * @param show_bar Show progress bar
 * @param show_text Show text percentage
 */
void task_progress_init_custom(int16_t x, int16_t y,
                               int16_t bar_x, int16_t bar_y,
                               bool show_bar, bool show_text);

/**
 * @brief Shutdown progress display
 */
void task_progress_done(void);

// ============================================================================
// PROGRESS DISPLAY
// ============================================================================

/**
 * @brief Start progress display
 * 
 * @param message Status message (e.g., "Converting PNG")
 * @param max Maximum value (usually 100 for percentage)
 */
void task_progress_start(const char* message, uint8_t max);

/**
 * @brief Update progress
 * 
 * @param current Current value (0 to max)
 */
void task_progress_update(uint8_t current);

/**
 * @brief Update progress with message
 * 
 * @param current Current value
 * @param message New message (NULL to keep current)
 */
void task_progress_update_msg(uint8_t current, const char* message);

/**
 * @brief Increment progress by 1
 */
void task_progress_inc(void);

/**
 * @brief Complete progress (shows 100%)
 */
void task_progress_complete(void);

// ============================================================================
// SIMPLE TEXT-ONLY PROGRESS (uses least RAM)
// ============================================================================

/**
 * @brief Show simple text progress (no bar, minimal RAM)
 * 
 * @param message Message to show
 * @param percent Percentage (0-100)
 */
void task_progress_text(const char* message, uint8_t percent);

/**
 * @brief Clear progress text
 */
void task_progress_text_clear(void);

// ============================================================================
// LOW-RAM VERSIONS (< 10KB available)
// ============================================================================

/**
 * @brief Minimal progress display for low RAM situations
 * 
 * Only shows text, no bar, no state tracking.
 * Uses ~100 bytes of stack.
 * 
 * @param message Message to display
 * @param percent Current percentage
 */
void task_progress_minimal(const char* message, uint8_t percent);

/**
 * @brief Clear minimal progress
 */
void task_progress_minimal_clear(void);

// ============================================================================
// TFT INSTANCE MANAGEMENT
// ============================================================================

/**
 * @brief Set the TFT instance for progress display
 * 
 * @param tft TFT instance pointer
 */
void task_progress_set_tft(void* tft);

/**
 * @brief Get the current TFT instance
 * 
 * @return TFT instance pointer or NULL
 */
void* task_progress_get_tft(void);

#endif // TASK_PROGRESS_H
